import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import { chmodSync, cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readlinkSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import test from 'node:test'
import { initialize, sync, plan, verify, status, boundaryIssues, names, originIdentity } from '../hep-lab-space.mts'

const git = (path, ...args) => execFileSync('git', ['-C', path, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
const save = (path, value) => writeFileSync(path, JSON.stringify(value, null, 2) + '\n')
function fixture(t) {
  const temp = mkdtempSync(join(tmpdir(), 'hep-context-test-')), root = join(temp, 'lab')
  t.after(() => rmSync(temp, { recursive: true, force: true }))
  mkdirSync(join(root, '.hep-lab'), { recursive: true }); writeFileSync(join(root, 'AGENTS.md'), 'development\n')
  const repositories = {}
  for (const [key, name] of Object.entries(names)) {
    const source = join(temp, name); mkdirSync(source)
    git(source, 'init', '-b', 'main'); git(source, 'config', 'user.name', 'Context Test'); git(source, 'config', 'user.email', 'test@example.invalid')
    writeFileSync(join(source, 'AGENTS.md'), key === 'platform_manager_dsh_home' ? 'runtime identity\n' : 'development\n')
    if (key === 'platform_manager_dsh_home') writeFileSync(join(source, 'AGENTS.override.md'), 'developer identity\n')
    git(source, 'add', '.'); git(source, 'commit', '-qm', 'fixture')
    repositories[key] = { url: source, ref: 'main', commit: git(source, 'rev-parse', 'HEAD') }
  }
  const pack = join(root, 'skills/demo'), target = join(root, '.agents/skills/demo')
  mkdirSync(join(pack, 'references'), { recursive: true }); mkdirSync(join(pack, 'scripts'))
  writeFileSync(join(pack, 'SKILL.md'), '---\nname: demo\ndescription: shared test method\n---\nRead references/detail.md\n')
  writeFileSync(join(pack, 'references/detail.md'), 'resource\n'); writeFileSync(join(pack, 'scripts/run'), '#!/bin/sh\nexit 0\n'); chmodSync(join(pack, 'scripts/run'), 0o755)
  const config = { schema_version: 1, mode: 'symlink', repositories, skills: [{ name: 'demo', repository: 'workspace', path: 'skills/demo', scope: 'test task' }] }
  const configPath = join(root, '.hep-lab/sources.json'); save(configPath, config)
  return { temp, root, pack, target, config, configPath }
}
test('首次克隆固定提交，真实包资源与可执行权限可达；重复 init/sync 不改写', t => {
  const f = fixture(t), first = initialize(f.root)
  assert.equal(first.changed, true); assert.deepEqual(first.warnings, [])
  for (const [key, name] of Object.entries(names)) assert.equal(git(join(f.root, name), 'rev-parse', 'HEAD'), f.config.repositories[key].commit)
  assert.equal(readlinkSync(f.target), '../../skills/demo')
  assert.equal(readFileSync(join(f.target, 'references/detail.md'), 'utf8'), 'resource\n')
  const manifest = join(f.root, '.hep-lab/manifest.json'), runtime = join(f.root, 'hep-lab.yaml')
  const before = [readFileSync(manifest, 'utf8'), statSync(manifest).mtimeMs, statSync(runtime).mtimeMs]
  assert.equal(initialize(f.root).changed, false); assert.equal(sync(f.root).changed, false)
  assert.deepEqual([readFileSync(manifest, 'utf8'), statSync(manifest).mtimeMs, statSync(runtime).mtimeMs], before)
  assert.equal(verify(f.root).valid, true)
  assert.equal(readFileSync(join(f.root, names.platform_manager_dsh_home, 'AGENTS.md'), 'utf8'), 'runtime identity\n')
})
test('复制整个包、保留脚本权限；源变化显示漂移且支持复制和链接双向切换', t => {
  const f = fixture(t); initialize(f.root); sync(f.root, 'copy')
  assert.equal(lstatSync(f.target).isDirectory(), true)
  assert.equal(statSync(join(f.target, 'scripts/run')).mode & 0o111, 0o111)
  assert.equal(verify(f.root).valid, true)
  assert.equal(plan(f.root).changes.length, 0)
  assert.equal(sync(f.root).changed, false)
  writeFileSync(join(f.pack, 'references/detail.md'), 'new resource\n')
  assert.equal(verify(f.root).valid, false)
  const change = plan(f.root, 'copy').changes[0]
  assert.notEqual(change.old.source_hash, change.next.source_hash)
  sync(f.root, 'copy')
  assert.equal(readFileSync(join(f.target, 'references/detail.md'), 'utf8'), 'new resource\n')
  assert.equal(sync(f.root, 'copy').changed, false)
  sync(f.root, 'symlink'); assert.equal(lstatSync(f.target).isSymbolicLink(), true)
})
test('复制目标手工修改不覆盖，冲突发生前其他目标也不写入', t => {
  const f = fixture(t); initialize(f.root); sync(f.root, 'copy')
  writeFileSync(join(f.target, 'references/detail.md'), 'user change\n')
  const next = join(f.root, 'skills/second'); cpSync(f.pack, next, { recursive: true })
  writeFileSync(join(next, 'SKILL.md'), '---\nname: second\ndescription: second task\n---\n')
  f.config.skills.push({ name: 'second', repository: 'workspace', path: 'skills/second', scope: 'second task' }); save(f.configPath, f.config)
  assert.throws(() => sync(f.root, 'copy'), /手工修改/)
  assert.equal(readFileSync(join(f.target, 'references/detail.md'), 'utf8'), 'user change\n')
  assert.equal(existsSync(join(f.root, '.agents/skills/second')), false)
})
